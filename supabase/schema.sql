-- Jalankan di: Supabase Dashboard > SQL Editor
-- =====================================================

-- =====================================================
-- 1. TABEL PRODUK
-- =====================================================

CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL,
    caliber TEXT,
    price NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (price >= 0),
    description TEXT,
    specs JSONB NOT NULL DEFAULT '[]'::jsonb,
    image_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =====================================================
-- 2. TABEL ULASAN DAN RATING
-- =====================================================

CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL
        REFERENCES public.products(id) ON DELETE CASCADE,
    user_id UUID NOT NULL,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (product_id, user_id)
);

-- =====================================================
-- 3. TABEL FAVORIT
-- =====================================================

CREATE TABLE IF NOT EXISTS public.favorites (
    user_id UUID NOT NULL,
    product_id BIGINT NOT NULL
        REFERENCES public.products(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, product_id)
);

-- =====================================================
-- 4. HAPUS FOREIGN KEY USER_ID JIKA SUDAH ADA
--    Agar user_id dapat berupa UUID tanpa akun Auth.
-- =====================================================

ALTER TABLE public.favorites
    DROP CONSTRAINT IF EXISTS favorites_user_id_fkey;

ALTER TABLE public.reviews
    DROP CONSTRAINT IF EXISTS reviews_user_id_fkey;

-- =====================================================
-- 5. AKTIFKAN ROW LEVEL SECURITY
-- =====================================================

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.favorites ENABLE ROW LEVEL SECURITY;

-- =====================================================
-- 6. HAK AKSES TABEL
-- =====================================================

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.products TO anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.reviews TO anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.favorites TO anon, authenticated;

GRANT USAGE, SELECT
ON SEQUENCE public.products_id_seq TO anon, authenticated;

GRANT USAGE, SELECT
ON SEQUENCE public.reviews_id_seq TO anon, authenticated;

-- =====================================================
-- 7. HAPUS POLICY LAMA YANG DIBUAT DI BAGIAN SEBELUMNYA
-- =====================================================

DROP POLICY IF EXISTS "Products are publicly readable"
ON public.products;

DROP POLICY IF EXISTS "Authenticated users can create products"
ON public.products;

DROP POLICY IF EXISTS "Authenticated users can update products"
ON public.products;

DROP POLICY IF EXISTS "Authenticated users can delete products"
ON public.products;

DROP POLICY IF EXISTS "Reviews are publicly readable"
ON public.reviews;

DROP POLICY IF EXISTS "Users can create their own reviews"
ON public.reviews;

DROP POLICY IF EXISTS "Users can update their own reviews"
ON public.reviews;

DROP POLICY IF EXISTS "Users can delete their own reviews"
ON public.reviews;

DROP POLICY IF EXISTS "Users can read their own favorites"
ON public.favorites;

DROP POLICY IF EXISTS "Users can add their own favorites"
ON public.favorites;

DROP POLICY IF EXISTS "Users can remove their own favorites"
ON public.favorites;

DROP POLICY IF EXISTS "Allow public all on products"
ON public.products;

DROP POLICY IF EXISTS "Allow public all on reviews"
ON public.reviews;

DROP POLICY IF EXISTS "Allow public all on favorites"
ON public.favorites;

-- =====================================================
-- 8. AKSES PUBLIK PENUH SESUAI QUERY TERAKHIR
-- =====================================================

CREATE POLICY "Allow public all on products"
ON public.products
FOR ALL
TO anon
USING (true)
WITH CHECK (true);

CREATE POLICY "Allow public all on reviews"
ON public.reviews
FOR ALL
TO anon
USING (true)
WITH CHECK (true);

CREATE POLICY "Allow public all on favorites"
ON public.favorites
FOR ALL
TO anon
USING (true)
WITH CHECK (true);

-- Pengguna authenticated juga diberi akses penuh,
-- sesuai hak akses pada query terakhir.
CREATE POLICY "Allow authenticated all on products"
ON public.products
FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);

CREATE POLICY "Allow authenticated all on reviews"
ON public.reviews
FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);

CREATE POLICY "Allow authenticated all on favorites"
ON public.favorites
FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);

-- =====================================================
-- 9. STORAGE: IZIN UPLOAD, UPDATE, DELETE
--    Pastikan bucket product-images sudah dibuat.
-- =====================================================

DROP POLICY IF EXISTS
"Authenticated users can upload product images"
ON storage.objects;

DROP POLICY IF EXISTS
"Authenticated users can update product images"
ON storage.objects;

DROP POLICY IF EXISTS
"Authenticated users can delete product images"
ON storage.objects;

CREATE POLICY "Authenticated users can upload product images"
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (bucket_id = 'product-images');

CREATE POLICY "Authenticated users can update product images"
ON storage.objects
FOR UPDATE
TO authenticated
USING (bucket_id = 'product-images')
WITH CHECK (bucket_id = 'product-images');

CREATE POLICY "Authenticated users can delete product images"
ON storage.objects
FOR DELETE
TO authenticated
USING (bucket_id = 'product-images');

